// Generates supabase/seed.sql (sample shops, sample reviews, ~70 days of demo activity)
// from the app's own catalogue so both stay in sync.   Usage: node supabase/gen-seed.mjs
import { writeFileSync } from 'node:fs';
import { BASE_SHOPS, SAMPLE_REVIEWS, sampleGenReviews } from '../js/data.js';

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const j = (o) => `${q(JSON.stringify(o))}::jsonb`;
const out = [];
out.push('-- Generated by supabase/gen-seed.mjs — sample data for Pointie. Safe to re-run (replaces demo rows).');
out.push('begin;');

// ---- shops
for (const s of BASE_SHOPS) {
  const { id, ...data } = s;
  out.push(`insert into public.shops (id, data, sample) values (${q(id)}, ${j(data)}, true)
  on conflict (id) do update set data = excluded.data, sample = true;`);
}

// ---- sample reviews (shown in the store page)
out.push("delete from public.reviews where sample;");
for (const [shop, list] of Object.entries(SAMPLE_REVIEWS)) {
  list.forEach((r, i) => {
    out.push(`insert into public.reviews (shop_id, customer_id, nick, lv, stars, text, sample, created_at)
  values (${q(shop)}, null, ${q(r.name)}, ${r.lv}, ${r.stars}, ${q(r.text)}, true, now() - interval '${(i + 1) * 3} days');`);
  });
}

// sample written reviews per generation (tap a generation on the store page to read them)
BASE_SHOPS.forEach((s, si) => {
  for (const r of sampleGenReviews(s, si)) {
    out.push(`insert into public.reviews (shop_id, customer_id, nick, lv, stars, text, sample, gen, created_at)
  values (${q(s.id)}, null, ${q(r.name)}, ${r.lv}, ${r.stars}, ${q(r.text)}, true, ${q(r.gen)}, now() - interval '${r.daysAgo} days');`);
  }
});

// ---- demo activity for dashboards (deterministic)
const NICKS = ['ปอนด์', 'นุ่น', 'ต้น', 'ฟ้า', 'บอส', 'มิ้นท์', 'เจ', 'แพร', 'กิ๊ฟ', 'เบล', 'ออม', 'ภูมิ', 'ใบเตย', 'ไอซ์', 'แบงค์', 'พลอย', 'ก้อง', 'น้ำ', 'ปาล์ม', 'เฟิร์น',
  'โอ๊ต', 'แนน', 'ตาล', 'กาย', 'ข้าวหอม', 'เอิร์ธ', 'มุก', 'ฝน', 'บีม', 'ปั้น', 'จูน', 'เกด', 'นัท', 'โบว์', 'ภีม', 'หลิว', 'ต่อ', 'นิว', 'แอน', 'อาร์ม'];
let seed = 20261104 >>> 0;
const r = () => { seed = (seed * 1664525 + 1013904223) >>> 0; return seed / 4294967296; };
const hours = { cafe: [8, 8, 9, 9, 10, 11, 13, 15, 16, 17], food: [11, 11, 12, 12, 12, 13, 13, 17, 18, 19], shop: [11, 13, 14, 15, 16, 17, 18, 19], act: [13, 15, 17, 18, 19, 19, 20, 20] };
const events = []; const reds = [];
for (const s of BASE_SHOPS) {
  const pop = { baan: 7, jae: 9, noodle: 6, roast: 5, plant: 3, climb: 3, book: 2, clay: 2 }[s.id] || 3;
  // generation mix per kind of shop (demo only): cafés skew Gen Z/Y, food is broader
  const mix = { cafe: [['z', .45], ['y', .38], ['x', .13], ['boomer', .04]], food: [['z', .25], ['y', .35], ['x', .27], ['boomer', .13]],
    shop: [['z', .30], ['y', .37], ['x', .23], ['boomer', .10]], act: [['z', .52], ['y', .36], ['x', .10], ['boomer', .02]] }[s.cat];
  const pickGen = () => { let x = r(); for (const [g, w] of mix) { if ((x -= w) <= 0) return g; } return 'y'; };
  const pool = [...NICKS, ...NICKS.map((n) => `${n} ${'กขคจชดตนบปพมรสอ'[Math.floor(r() * 15)]}.`)].map((n, i) => ({ id: `demo:${s.id}:${i}`, nick: n, gen: pickGen() }));
  // each generation leans a little differently on each shop, so the per-gen emojis differ
  const lean = Object.fromEntries(['z', 'y', 'x', 'boomer'].map((g) => [g, r()]));
  const st = new Map();
  for (let d = 69; d >= 0; d--) {
    const wk = (new Date(Date.UTC(2026, 0, 1)).getUTCDay() + d) % 7; // only used to vary volume
    const n = Math.round(pop * (0.6 + r() * 0.8) * (wk === 0 || wk === 6 ? 1.3 : 1));
    const used = new Set();
    for (let k = 0; k < n; k++) {
      const c = pool[Math.floor(Math.pow(r(), 1.25) * pool.length)];
      if (used.has(c.id)) continue; used.add(c.id);
      const hrs = hours[s.cat]; const h = hrs[Math.floor(r() * hrs.length)]; const m = Math.floor(r() * 60);
      // timestamp relative to "now" at load time, in Bangkok local hours
      const at = `(date_trunc('day', now() at time zone 'Asia/Bangkok') - interval '${d} days' + interval '${h} hours ${m} minutes') at time zone 'Asia/Bangkok'`;
      const cur = st.get(c.id) || { have: 0 };
      if (cur.have >= s.card.need) {
        reds.push(`(${q(s.id)}, ${q(c.nick)}, ${q(s.card.reward)}, ${q(String(1000 + Math.floor(r() * 9000)))}, 'confirmed', ${at} - interval '1 minute', ${at})`);
        events.push(`(${q(s.id)}, ${q(c.id)}, ${q(c.nick)}, 'redeem', null, null, null, ${at} - interval '1 minute', ${q(c.gen)})`);
        cur.have = 0;
      }
      cur.have += 1; st.set(c.id, cur);
      events.push(`(${q(s.id)}, ${q(c.id)}, ${q(c.nick)}, 'stamp', 1, ${cur.have}, null, ${at}, ${q(c.gen)})`);
      if (r() < 0.09) {
        const x = r() * 0.6 + lean[c.gen] * 0.55; // 0..1.15 → 3..5 stars
        const stars = x > 0.75 ? 5 : x > 0.42 ? 4 : 3;
        events.push(`(${q(s.id)}, ${q(c.id)}, ${q(c.nick)}, 'review', null, null, ${stars}, ${at} + interval '1 hour', ${q(c.gen)})`);
      }
    }
  }
}
out.push('delete from public.events where demo;');
out.push("delete from public.redemptions where customer_id is null and status = 'confirmed' and shop_id in (select id from public.shops where sample);");
for (let i = 0; i < events.length; i += 500) {
  out.push(`insert into public.events (shop_id, customer_key, nick, type, n, have, stars, created_at, gen) values\n${events.slice(i, i + 500).join(',\n')};`);
}
out.push('update public.events set demo = true where customer_id is null;');
for (let i = 0; i < reds.length; i += 500) {
  out.push(`insert into public.redemptions (shop_id, nick, reward, code, status, created_at, confirmed_at) values\n${reds.slice(i, i + 500).join(',\n')};`);
}
out.push('-- drop demo rows that landed in the future (later today)');
out.push('delete from public.events where demo and created_at > now();');
out.push('commit;');
writeFileSync(new URL('./seed.sql', import.meta.url), out.join('\n') + '\n');
console.log(`seed.sql: ${BASE_SHOPS.length} shops, ${events.length} events, ${reds.length} redemptions`);
